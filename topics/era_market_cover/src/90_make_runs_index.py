"""Builds repro/RUNS.md: an index of every script in src/ with its first docstring/comment line and its usage line, and, for each WORKLOG.md entry, the scripts and result files cited in its heading. Everything is read from the files; nothing is typed by hand.
usage: python src/90_make_runs_index.py"""
import glob, os, re
def head(p):
    t = open(p, errors="ignore").read().split("\n"); doc, use = "", ""
    if p.endswith(".py"):
        m = re.match(r'\s*r?"""(.*)', t[0]) if t else None
        body = "\n".join(t[:40]); m = re.match(r'\s*r?"""(.*?)(\n|""")', body, re.S)
        if m: doc = m.group(1).strip()
        u = re.search(r"usage:\s*([^\n]*)", body); use = u.group(1).strip().rstrip('"') if u else ""
    else:
        c = [l.lstrip("# ").strip() for l in t[:6] if l.startswith("#") and not l.startswith("#!")]
        doc = c[0] if c else ""; u = [x for x in c if x.startswith("usage")]; use = u[0][6:].strip(" :") if u else ""
    return doc[:230].replace("|", "/"), use[:160].replace("|", "/")
L = ["# Run index (generated by src/90_make_runs_index.py; do not edit by hand)", "",
     "Environment: see `environment.txt`. Server layout: `~/era_market` with `src/` (these scripts), `venv*` (python environments per tool family), `results/` (json outputs, copied into `results/` of this repo except `.npz` embeddings), `gen_*` directories (generated audio, not in the repo).", "",
     "## Scripts", "", "| script | what it does (first line of its header) | usage |", "|---|---|---|"]
for p in sorted(glob.glob("src/*.py") + glob.glob("src/*.sh")):
    d, u = head(p); L.append(f"| `{os.path.basename(p)}` | {d} | {u} |")
L += ["", "## WORKLOG entries and the scripts / result files named in their headings", ""]
for l in open("WORKLOG.md"):
    if l.startswith("## "):
        refs = sorted(set(re.findall(r"\b(?:src/)?([0-9A-Za-z_]+\.(?:py|sh))\b", l)))
        L.append(f"- {l[3:].strip()[:300]}" + (f"  \n  scripts: {', '.join(refs)}" if refs else ""))
open("repro/RUNS.md", "w").write("\n".join(L) + "\n"); print(len(L), "lines")
